/*
가장 먼저 생각난 방법은 매번 큰 수를 찾은 뒤 작은 원소들을 증가시키며 모든 원소가 같아될 때까지 반복하는것
다만, 손으로 해봤을 때, 매번 큰 원소를 찾고 작은 원소들을 증가시키는 방법은 횟수가 너무 많다고 생각한다
보통 이런 문제는 규칙성이 존재하고 해당 규칙성에 맞는 공식을 찾아내야한다

(20분 고민해봤지만 공식이 떠오르지 않음... AI에게 도움받음ㅜ)

'n-1개를 +1'하는건 '1개만 -1'하는 것과 같다
문제에 나온 것처럼 +1을 한 다음에 모든 원소에서 1을 빼보자
+1을 한 원소는 +1이 -1이 되어 다시 돌아오고 +1을 못 받은 원소만 -1 된다
또한, 모든 원소에서 똑같이 1을 빼는 건 '서로 같은가'를 판단하는 데 아무 영향이 없다
즉, n-1개를 1씩 올리는 대신 하나의 원소만 1씩 내리는 쪽으로 세도 최소 이동 횟수는 같다
결국 이 문제는 '전부 최솟값까지 내리기'로 바뀐다
최솟값으로 목표가 바뀐 이유는 모든 값을 동일하게 맞추면 끝나기에 최솟값보다 더 내려갈 이유가 없기 때문에
*/
class Solution {
public:
    int minMoves(vector<int>& nums) {
        int min = *min_element(nums.begin(), nums.end());
        int moves = 0;

        for (int num : nums) {
            moves += num - min;
        }

        return moves;
    }
};
